// Writes lib/survey/figtree-metrics.generated.ts from the print font files in public/fonts/figtree,
// so the layout engine can measure text without loading a font. Run `npm run survey:metrics`
// after replacing a font file; tests/unit/survey-text-metrics.test.ts fails until you do.

import fs from "node:fs";
import path from "node:path";
import fontkit from "@pdf-lib/fontkit";

import { PRINT_FONT_FILES } from "#/lib/survey/print-fonts";

const root = path.resolve(import.meta.dirname, "../..");
const out = path.join(root, "lib/survey/figtree-metrics.generated.ts");

const fonts = Object.entries(PRINT_FONT_FILES).map(([weight, file]) => ({
  weight,
  font: fontkit.create(fs.readFileSync(path.join(root, "public/fonts/figtree", file))),
}));

/**
 * Characters every weight can print on its own: no control characters, and no combining accents,
 * which need mark positioning the print layout turns off.
 */
function printable(codePoint: number) {
  const control = codePoint < 0x20 || (codePoint >= 0x7f && codePoint < 0xa0);
  const combining = codePoint >= 0x300 && codePoint < 0x370;
  return !control && !combining && codePoint !== 0xffff;
}

const [first] = fonts;
if (!first) {
  throw new Error("No print fonts");
}
const codePoints = first.font.characterSet
  .filter(printable)
  .filter((codePoint) => fonts.every(({ font }) => font.hasGlyphForCodePoint(codePoint)))
  .toSorted((a, b) => a - b);

const advances = Object.fromEntries(
  fonts.map(({ weight, font }) => [
    weight,
    codePoints.map((codePoint) => font.glyphForCodePoint(codePoint).advanceWidth),
  ]),
);

const metrics = {
  unitsPerEm: first.font.unitsPerEm,
  capHeight: first.font.capHeight,
  codePoints,
  advances,
};

fs.writeFileSync(
  out,
  `// Generated by scripts/survey/generate-figtree-metrics.ts from public/fonts/figtree. Do not edit.

export const FIGTREE_METRICS: {
  unitsPerEm: number;
  /** The height of a capital letter above the baseline, in font units. */
  capHeight: number;
  /** Every character the print fonts have, ascending. */
  codePoints: number[];
  /** Advance widths in font units, per weight, in the order of \`codePoints\`. */
  advances: Record<400 | 600 | 700, number[]>;
} = ${JSON.stringify(metrics)};
`,
);
console.log(`Wrote ${codePoints.length} characters to ${path.relative(root, out)}`);
